"""Generate dummy orders (seed SQL) and an Excel correction file with intentional errors.

Usage:
    python src/generate_sample_data.py
Outputs:
    sql/02_seed_orders.sql
    data/sample/order_corrections_sample.xlsx
"""
import random
from datetime import date, timedelta
from pathlib import Path

import pandas as pd

random.seed(42)
ROOT = Path(__file__).resolve().parents[1]
STATUSES = ["PENDING", "PROCESSING", "SHIPPED", "DELIVERED", "CANCELLED"]
NUM_ORDERS = 500


def build_orders() -> list[dict]:
    orders = []
    for order_id in range(1001, 1001 + NUM_ORDERS):
        order_date = date(2026, 1, 1) + timedelta(days=random.randint(0, 300))
        status = random.choice(STATUSES)
        ship_date = (
            order_date + timedelta(days=random.randint(1, 10))
            if status in ("SHIPPED", "DELIVERED") else None
        )
        orders.append({
            "OrderID": order_id,
            "CustomerID": random.randint(1, 120),
            "OrderDate": order_date,
            "OrderStatus": status,
            "ShipDate": ship_date,
            "Amount": round(random.uniform(10, 2000), 2),
        })
    return orders


def write_seed_sql(orders: list[dict]) -> Path:
    lines = [
        "/* 02_seed_orders.sql - generated by src/generate_sample_data.py */",
        "USE DataCorrectionDemo;",
        "GO",
        "DELETE FROM dbo.Orders;",
    ]
    for o in orders:
        ship = f"'{o['ShipDate']}'" if o["ShipDate"] else "NULL"
        lines.append(
            "INSERT INTO dbo.Orders (OrderID, CustomerID, OrderDate, OrderStatus, ShipDate, Amount) "
            f"VALUES ({o['OrderID']}, {o['CustomerID']}, '{o['OrderDate']}', "
            f"'{o['OrderStatus']}', {ship}, {o['Amount']});"
        )
    lines.append("GO")
    out = ROOT / "sql" / "02_seed_orders.sql"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def build_corrections(orders: list[dict]) -> pd.DataFrame:
    # Keep error-test orders out of the valid sample to avoid overlap
    error_ids = {1001, 1002, 1003, 1004, 1005}
    pool = [o for o in orders if o["OrderID"] not in error_ids]

    rows = []
    # 20 valid corrections
    for o in random.sample(pool, 20):
        new_ship = o["OrderDate"] + timedelta(days=random.randint(1, 7))
        rows.append({"OrderID": o["OrderID"], "NewOrderStatus": "SHIPPED",
                     "NewShipDate": new_ship.isoformat(), "RequestedBy": "ops.user1"})

    first = orders[0]  # OrderID 1001
    rows += [
        # non-numeric OrderID
        {"OrderID": "ABC", "NewOrderStatus": "SHIPPED", "NewShipDate": "2026-05-01", "RequestedBy": "ops.user2"},
        # OrderID not found
        {"OrderID": 99999, "NewOrderStatus": "SHIPPED", "NewShipDate": "2026-05-01", "RequestedBy": "ops.user2"},
        # invalid status
        {"OrderID": 1002, "NewOrderStatus": "SHIPED", "NewShipDate": "2026-05-01", "RequestedBy": "ops.user2"},
        # invalid date
        {"OrderID": 1003, "NewOrderStatus": "SHIPPED", "NewShipDate": "31/31/2026", "RequestedBy": "ops.user2"},
        # ship date before order date
        {"OrderID": first["OrderID"], "NewOrderStatus": "SHIPPED",
         "NewShipDate": (first["OrderDate"] - timedelta(days=5)).isoformat(), "RequestedBy": "ops.user2"},
        # nothing to change
        {"OrderID": 1004, "NewOrderStatus": None, "NewShipDate": None, "RequestedBy": "ops.user2"},
        # missing requester
        {"OrderID": 1005, "NewOrderStatus": "DELIVERED", "NewShipDate": "2026-06-01", "RequestedBy": None},
    ]
    # duplicate OrderID in same batch
    rows.append(dict(rows[0]))

    df = pd.DataFrame(rows, columns=["OrderID", "NewOrderStatus", "NewShipDate", "RequestedBy"])
    df["OrderID"] = df["OrderID"].astype(str)  # keep mixed values as text
    return df.sample(frac=1, random_state=7).reset_index(drop=True)


def main() -> None:
    (ROOT / "sql").mkdir(exist_ok=True)
    sample_dir = ROOT / "data" / "sample"
    sample_dir.mkdir(parents=True, exist_ok=True)

    orders = build_orders()
    seed = write_seed_sql(orders)

    out_file = sample_dir / "order_corrections_sample.xlsx"
    df = build_corrections(orders)
    df.to_excel(out_file, index=False, sheet_name="Corrections")

    print(f"Seed SQL   : {seed.relative_to(ROOT)} ({len(orders)} orders)")
    print(f"Excel file : {out_file.relative_to(ROOT)} ({len(df)} rows)")


if __name__ == "__main__":
    main()
